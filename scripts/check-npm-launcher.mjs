#!/usr/bin/env node
// Proof harness for issue #2016: the npm launcher must resolve the executable
// inside the extracted macOS .app bundle. Not shipped (it lives outside npm/ and
// outside npm/package.json#files); run it directly with node.
//
// Usage:
//   node scripts/check-npm-launcher.mjs [--work-dir <dir>] [--asset <agentscommander-mac-*.app.tar.gz>] [--keep]
//
// Exit codes: 0 = no FAIL; 1 = at least one FAIL. A SKIP is reported with its
// reason and never fails the run.
//
// No network: npm pack runs with npm_config_cache redirected into the work dir,
// and install.js runs against an offline fixture HTTPS transport (stub.cjs).
//
// Layout of one run:
//   <work>/package.json        {"type":"commonjs"} marker (this repo is ESM)
//   <work>/run.js              byte-for-byte copy of npm/run.js
//   <work>/install.js          byte-for-byte copy of npm/install.js
//   <work>/resolve-bin.js      byte-for-byte copy of npm/resolve-bin.js
//   <work>/stub.cjs            preload: forces darwin/x64 + offline transport
//   <work>/fixture-ok/...      tarred into mac-ok.tar.gz        (I1)
//   <work>/fixture-incomplete/ tarred into mac-incomplete.tar.gz (I2)
//   <work>/bin/                recreated per scenario

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NPM_DIR = path.join(REPO_ROOT, 'npm');

// ---------- arguments ----------

const argv = process.argv.slice(2);
function argValue(name) {
  const i = argv.indexOf(name);
  return i === -1 ? undefined : argv[i + 1];
}
const keep = argv.includes('--keep');
const workDirArg = argValue('--work-dir');
const assetArg = argValue('--asset');

const workDir = workDirArg
  ? path.resolve(workDirArg)
  : fs.mkdtempSync(path.join(os.tmpdir(), 'ac-npm-launcher-'));
const binDir = path.join(workDir, 'bin');

// ---------- fixtures ----------

// Windows CreateProcess appends .exe to an extensionless application path, so a
// fixture executable named without the extension cannot be spawned on Windows.
const FIXTURE_EXE = process.platform === 'win32' ? 'renamed-exe.exe' : 'renamed-exe';
const NODE_BYTES = fs.readFileSync(process.execPath);
const CHILD_SCRIPT = "console.log('AC_MARKER:' + process.argv[1])";
const COPIED_FILES = ['run.js', 'install.js', 'resolve-bin.js'];

const STUB_SOURCE = `// Generated by scripts/check-npm-launcher.mjs for issue #2016. Do not edit.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const os = require('os');
const https = require('https');
const { Readable } = require('stream');

const platform = process.env.I2016_PLATFORM || 'darwin';
const fixtureName = process.env.I2016_FIXTURE || 'mac-ok.tar.gz';
const fixturePath = path.join(__dirname, fixtureName);
const ASSET_NAME = 'agentscommander-mac-x86_64.app.tar.gz';

os.platform = () => platform;
os.arch = () => 'x64';

https.get = function (url, options, callback) {
  if (typeof options === 'function') { callback = options; options = undefined; }
  let payload;
  if (String(url).indexOf('SHASUMS256.txt') !== -1) {
    const digest = crypto.createHash('sha256').update(fs.readFileSync(fixturePath)).digest('hex');
    payload = digest + '  ' + ASSET_NAME + '\\n';
  } else {
    payload = fs.readFileSync(fixturePath);
  }
  const res = Readable.from([payload]);
  res.statusCode = 200;
  res.headers = {};
  process.nextTick(() => callback(res));
  return { on() { return this; } };
};
`;

function plistXml(executable) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n' +
    '<plist version="1.0">\n<dict>\n' +
    '    <key>CFBundleExecutable</key>\n' +
    '    <string>' + executable + '</string>\n' +
    '    <key>CFBundleIdentifier</key>\n' +
    '    <string>dev.agentscommander.fixture</string>\n' +
    '</dict>\n</plist>\n';
}

function makeBundle(parentDir, options = {}) {
  const bundleName = options.bundleName || 'Renamed Bundle.app';
  const executable = options.executable || FIXTURE_EXE;
  const appDir = path.join(parentDir, bundleName);
  const macOSDir = path.join(appDir, 'Contents', 'MacOS');
  const plistPath = path.join(appDir, 'Contents', 'Info.plist');
  fs.mkdirSync(macOSDir, { recursive: true });
  fs.writeFileSync(
    plistPath,
    options.plistText !== undefined ? options.plistText : plistXml(executable),
  );
  const exePath = path.join(macOSDir, executable);
  if (options.exeBytes !== undefined) {
    fs.writeFileSync(exePath, options.exeBytes);
  }
  return { appDir, plistPath, exePath };
}

// ---------- results ----------

const results = [];
function record(id, status, detail = '') {
  results.push({ id, status, detail });
}
function test(id, fn) {
  try {
    const detail = fn();
    record(id, 'PASS', detail || '');
  } catch (err) {
    record(id, 'FAIL', err && err.message ? err.message : String(err));
  }
}
function skip(id, reason) {
  record(id, 'SKIP', reason);
}

function fail(message) {
  throw new Error(message);
}
function assert(cond, message) {
  if (!cond) fail(message);
}
function assertIncludes(haystack, needle, label) {
  assert(
    typeof haystack === 'string' && haystack.includes(needle),
    `${label}: expected text containing ${JSON.stringify(needle)}; got ${JSON.stringify(haystack)}`,
  );
}
function assertThrows(fn, needles, label) {
  let message = null;
  try {
    fn();
  } catch (err) {
    message = err && err.message ? err.message : String(err);
  }
  assert(message !== null, `${label}: expected a throw, but the call succeeded`);
  for (const needle of needles) assertIncludes(message, needle, `${label} thrown message`);
  return message;
}
function expectEqual(actual, expected, label) {
  assert(actual === expected, `${label}: expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`);
}
function expectExit(r, code, label) {
  assert(
    r.status === code,
    `${label}: expected exit ${code}, got ${r.status}` +
      (r.error ? ` (spawn error: ${r.error.message})` : '') +
      `; stderr=${JSON.stringify(r.stderr)}; stdout=${JSON.stringify(r.stdout)}`,
  );
}
function assertHint(stderr, label) {
  assertIncludes(stderr, '--ignore-scripts', label);
  assertIncludes(stderr, 'npm rebuild -g @mblua/agentscommander', label);
}

// ---------- work dir ----------

let ownsWorkDir = false;

function prepareWorkDir() {
  if (workDirArg) {
    if (fs.existsSync(workDir)) {
      const entries = fs.readdirSync(workDir);
      if (entries.length > 0) {
        console.error(`ERROR: --work-dir must be absent or empty: ${workDir}`);
        process.exit(1); // no finally: the caller's directory is left untouched
      }
    } else {
      fs.mkdirSync(workDir, { recursive: true });
    }
  }
  ownsWorkDir = true;
  // Load-bearing: this work dir sits inside a "type":"module" repository, so
  // without the marker every copied .js file would load as ESM.
  fs.writeFileSync(path.join(workDir, 'package.json'), '{"type":"commonjs"}\n');
  for (const name of COPIED_FILES) {
    const src = path.join(NPM_DIR, name);
    const content = fs.readFileSync(src);
    fs.writeFileSync(path.join(workDir, name), content);
    assert(
      fs.readFileSync(path.join(workDir, name)).equals(content),
      `copy of ${name} is not byte-identical to ${src}`,
    );
  }
  fs.writeFileSync(path.join(workDir, 'stub.cjs'), STUB_SOURCE);
}

function freshBin() {
  fs.rmSync(binDir, { recursive: true, force: true });
  fs.mkdirSync(binDir, { recursive: true });
}

// ---------- tar ----------

function resolveTar() {
  if (process.platform === 'win32') {
    const dir = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32');
    const exe = path.join(dir, 'tar.exe');
    return fs.existsSync(exe) ? { cmd: exe, dir } : null;
  }
  try {
    execFileSync('tar', ['--version'], { stdio: 'ignore' });
    return { cmd: 'tar', dir: null };
  } catch {
    return null;
  }
}

function prependPath(env, dir) {
  const key = Object.keys(env).find((k) => k.toLowerCase() === 'path') || 'Path';
  env[key] = `${dir};${env[key] || ''}`;
}

// ---------- launcher runs ----------

function runLauncher(launcherArgs, options = {}) {
  const forceDarwin = options.forceDarwin === true;
  const nodeArgs = forceDarwin
    ? ['-r', path.join(workDir, 'stub.cjs'), path.join(workDir, 'run.js'), ...launcherArgs]
    : [path.join(workDir, 'run.js'), ...launcherArgs];
  const env = { ...process.env };
  if (forceDarwin) env.I2016_PLATFORM = 'darwin';
  Object.assign(env, options.env || {});
  return spawnSync(process.execPath, nodeArgs, { cwd: workDir, env, encoding: 'utf8' });
}

function runInstall(fixture, tarInfo) {
  const env = { ...process.env, I2016_PLATFORM: 'darwin', I2016_FIXTURE: fixture };
  if (tarInfo.dir) prependPath(env, tarInfo.dir);
  return spawnSync(
    process.execPath,
    ['-r', path.join(workDir, 'stub.cjs'), './install.js'],
    { cwd: workDir, env, encoding: 'utf8' },
  );
}

function assertNoInstallLeftovers(label) {
  const leftovers = fs.readdirSync(binDir).filter(
    (name) => name.endsWith('.tmp') || name.startsWith('SHASUMS256.txt') || name === 'tmp-extract',
  );
  assert(leftovers.length === 0, `${label}: unexpected leftovers in bin/: ${leftovers.join(', ')}`);
}

// ---------- the checks ----------

function runAllChecks() {
  const requireFromWork = createRequire(path.join(workDir, 'check.cjs'));
  const { resolveBinPath, assertExecutable } = requireFromWork(path.join(workDir, 'resolve-bin.js'));

  const darwinPaths = () => {
    const appDir = path.join(binDir, 'Renamed Bundle.app');
    return {
      appDir,
      plistPath: path.join(appDir, 'Contents', 'Info.plist'),
      exePath: path.join(appDir, 'Contents', 'MacOS', FIXTURE_EXE),
    };
  };

  // --- resolution contract ---
  test('R1', () => expectEqual(resolveBinPath('linux', binDir), path.join(binDir, 'agentscommander'), 'R1'));
  test('R2', () => expectEqual(resolveBinPath('win32', binDir), path.join(binDir, 'agentscommander.exe'), 'R2'));

  test('R3', () => {
    freshBin();
    makeBundle(binDir, { exeBytes: Buffer.from('fixture executable placeholder\n') });
    expectEqual(resolveBinPath('darwin', binDir), darwinPaths().exePath, 'R3');
  });

  test('R4', () => {
    freshBin();
    const { appDir } = makeBundle(binDir, { exeBytes: Buffer.from('fixture executable placeholder\n') });
    fs.writeFileSync(path.join(binDir, 'Decoy.app'), 'not a directory');
    fs.writeFileSync(path.join(binDir, 'notes.txt'), 'ignored');
    fs.mkdirSync(path.join(appDir, 'Inner.app'), { recursive: true });
    expectEqual(resolveBinPath('darwin', binDir), darwinPaths().exePath, 'R4');
  });

  test('R5', () => {
    fs.rmSync(binDir, { recursive: true, force: true });
    assertThrows(() => resolveBinPath('darwin', binDir), [binDir], 'R5');
  });

  test('R6', () => {
    freshBin();
    assertThrows(() => resolveBinPath('darwin', binDir), ['expected exactly one', binDir], 'R6');
  });

  test('R7', () => {
    freshBin();
    fs.mkdirSync(path.join(binDir, 'A.app'), { recursive: true });
    fs.mkdirSync(path.join(binDir, 'B.app'), { recursive: true });
    assertThrows(() => resolveBinPath('darwin', binDir), ['expected exactly one', 'A.app', 'B.app'], 'R7');
  });

  test('R8', () => {
    freshBin();
    const { plistPath } = makeBundle(binDir, { exeBytes: Buffer.from('x') });
    fs.rmSync(plistPath);
    assertThrows(() => resolveBinPath('darwin', binDir), [plistPath], 'R8');
  });

  test('R9', () => {
    freshBin();
    const { plistPath } = makeBundle(binDir, {
      plistText: '<?xml version="1.0" encoding="UTF-8"?>\n<plist version="1.0">\n<dict>\n' +
        '<key>CFBundleIdentifier</key>\n<string>dev.agentscommander.fixture</string>\n' +
        '</dict>\n</plist>\n',
    });
    assertThrows(() => resolveBinPath('darwin', binDir), [plistPath], 'R9');
  });

  test('R10', () => {
    freshBin();
    makeBundle(binDir, { plistText: plistXml('') });
    assertThrows(() => resolveBinPath('darwin', binDir), [], 'R10');
  });

  test('R11', () => {
    freshBin();
    makeBundle(binDir, { plistText: plistXml('../evil') });
    assertThrows(() => resolveBinPath('darwin', binDir), [], 'R11');
  });

  test('R12', () => {
    freshBin();
    makeBundle(binDir, {
      plistText: '<?xml version="1.0" encoding="UTF-8"?>\n<plist version="1.0">\n<dict>\n' +
        '\t<key>CFBundleExecutable</key>\n\t<string>\n\t\t' + FIXTURE_EXE + '\n\t</string>\n' +
        '</dict>\n</plist>\n',
    });
    expectEqual(resolveBinPath('darwin', binDir), darwinPaths().exePath, 'R12');
  });

  // --- install-time validation function ---
  test('V1', () => {
    freshBin();
    makeBundle(binDir, { exeBytes: Buffer.from('fixture executable placeholder\n') });
    const resolved = assertExecutable('darwin', binDir);
    expectEqual(resolved, darwinPaths().exePath, 'V1');
    assert(resolved.endsWith(FIXTURE_EXE), `V1: resolved path must end in ${FIXTURE_EXE}`);
  });

  test('V2', () => {
    freshBin();
    const { exePath } = makeBundle(binDir, { exeBytes: Buffer.from('x') });
    fs.rmSync(exePath);
    assertThrows(() => assertExecutable('darwin', binDir), [exePath], 'V2');
  });

  test('V3', () => {
    freshBin();
    const { exePath } = makeBundle(binDir, { exeBytes: Buffer.from('x') });
    fs.rmSync(exePath);
    fs.mkdirSync(exePath);
    assertThrows(() => assertExecutable('darwin', binDir), ['not a regular file', exePath], 'V3');
  });

  // --- package plumbing ---
  test('P1', () => {
    const env = { ...process.env, npm_config_cache: path.join(workDir, 'npm-cache') };
    const r = spawnSync('npm pack --dry-run --json', {
      cwd: NPM_DIR,
      env,
      shell: true,
      encoding: 'utf8',
    });
    expectExit(r, 0, 'P1 npm pack');
    const start = r.stdout.indexOf('[');
    assert(start !== -1, `P1: no JSON in npm pack output: ${JSON.stringify(r.stdout)}`);
    const packed = JSON.parse(r.stdout.slice(start))[0];
    const files = packed.files.map((f) => f.path).sort();
    const expected = ['README.md', 'install.js', 'package.json', 'resolve-bin.js', 'run.js'];
    assert(
      JSON.stringify(files) === JSON.stringify(expected),
      `P1: packed files ${JSON.stringify(files)} != ${JSON.stringify(expected)}`,
    );
    const rootVersion = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf8')).version;
    assert(packed.version === rootVersion, `P1: packed version ${packed.version} != root package.json ${rootVersion}`);
  });

  test('P2', () => {
    const r = spawnSync(process.execPath, [path.join(REPO_ROOT, 'scripts', 'check-version-sync.mjs')], {
      cwd: REPO_ROOT,
      encoding: 'utf8',
    });
    expectExit(r, 0, 'P2');
  });

  test('P3', () => {
    const source = fs.readFileSync(path.join(NPM_DIR, 'run.js'), 'utf8');
    assert(!/open\s+-a/.test(source), 'P3: run.js must not use `open -a`');
    assert(
      !/copyFile|copyFileSync|cpSync|fs\.cp\b/.test(source),
      'P3: run.js must not copy the executable out of the bundle',
    );
  });

  // --- real published artifact (opt-in) ---
  const tarInfo = resolveTar();
  if (!assetArg) {
    skip('A1', 'no --asset supplied');
  } else if (!tarInfo) {
    skip('A1', 'no usable tar to extract the asset');
  } else {
    test('A1', () => {
      assert(fs.existsSync(assetArg), `A1: asset not found: ${assetArg}`);
      const base = path.basename(assetArg);
      fs.copyFileSync(assetArg, path.join(workDir, base));
      const realBin = path.join(workDir, 'real-bin');
      fs.rmSync(realBin, { recursive: true, force: true });
      fs.mkdirSync(realBin, { recursive: true });
      execFileSync(tarInfo.cmd, ['-xzf', base, '-C', 'real-bin'], { cwd: workDir, stdio: 'pipe' });
      const expected = path.join(realBin, 'Agents Commander.app', 'Contents', 'MacOS', 'agentscommander');
      expectEqual(resolveBinPath('darwin', realBin), expected, 'A1');
      assert(fs.statSync(expected).isFile(), `A1: resolved path is not a regular file: ${expected}`);
      return `resolved ${expected}`;
    });
  }

  // --- end-to-end launcher scenarios ---
  test('H1', () => {
    freshBin();
    if (process.platform === 'darwin') {
      makeBundle(binDir, { exeBytes: NODE_BYTES });
    } else {
      fs.copyFileSync(
        process.execPath,
        path.join(binDir, process.platform === 'win32' ? 'agentscommander.exe' : 'agentscommander'),
      );
    }
    const r = runLauncher(['-e', CHILD_SCRIPT, 'hello-arg']);
    expectExit(r, 0, 'H1');
    assertIncludes(r.stdout, 'AC_MARKER:hello-arg', 'H1 stdout');
  });

  test('H2', () => {
    freshBin();
    let expectedPath;
    if (process.platform === 'darwin') {
      const { exePath } = makeBundle(binDir, { exeBytes: NODE_BYTES });
      fs.rmSync(exePath);
      expectedPath = exePath;
    } else {
      expectedPath = path.join(
        binDir,
        process.platform === 'win32' ? 'agentscommander.exe' : 'agentscommander',
      );
    }
    const r = runLauncher([]);
    expectExit(r, 1, 'H2');
    assertIncludes(r.stderr, expectedPath, 'H2 stderr');
    assertHint(r.stderr, 'H2 stderr');
  });

  test('H3', () => {
    freshBin();
    makeBundle(binDir, { exeBytes: NODE_BYTES });
    const r = runLauncher(['-e', CHILD_SCRIPT, 'hello-arg'], { forceDarwin: true });
    expectExit(r, 0, 'H3');
    assertIncludes(r.stdout, 'AC_MARKER:hello-arg', 'H3 stdout');
  });

  test('H4', () => {
    freshBin();
    makeBundle(binDir, { exeBytes: NODE_BYTES });
    const r = runLauncher(['-e', 'process.exit(7)'], { forceDarwin: true });
    expectExit(r, 7, 'H4');
  });

  test('H5', () => {
    freshBin();
    const { exePath } = makeBundle(binDir, { exeBytes: NODE_BYTES });
    fs.rmSync(exePath);
    const r = runLauncher([], { forceDarwin: true });
    expectExit(r, 1, 'H5');
    assertIncludes(r.stderr, exePath, 'H5 stderr');
  });

  test('H6', () => {
    freshBin();
    const r = runLauncher([], { forceDarwin: true });
    expectExit(r, 1, 'H6');
    assertIncludes(r.stderr, 'expected exactly one', 'H6 stderr');
    assertIncludes(r.stderr, binDir, 'H6 stderr');
  });

  test('H7', () => {
    fs.rmSync(binDir, { recursive: true, force: true });
    const r = runLauncher([], { forceDarwin: true });
    expectExit(r, 1, 'H7');
    assertIncludes(r.stderr, 'cannot read', 'H7 stderr');
    assertIncludes(r.stderr, binDir, 'H7 stderr');
    assertHint(r.stderr, 'H7 stderr');
  });

  test('E7', () => {
    for (const name of COPIED_FILES) {
      const r = spawnSync(process.execPath, ['--check', path.join(NPM_DIR, name)], { encoding: 'utf8' });
      expectExit(r, 0, `E7 ${name}`);
    }
  });

  // --- the darwin branch of install.js, end to end ---
  const fixtureJobs = [
    { id: 'I1', fixture: 'mac-ok.tar.gz', source: 'fixture-ok' },
    { id: 'I2', fixture: 'mac-incomplete.tar.gz', source: 'fixture-incomplete' },
  ];
  let fixtureError = null;
  if (!tarInfo) {
    fixtureError = 'no usable tar for fixture creation/extraction';
  } else {
    try {
      for (const job of fixtureJobs) {
        const sourceRoot = path.join(workDir, job.source);
        fs.rmSync(sourceRoot, { recursive: true, force: true });
        const appDir = path.join(sourceRoot, 'Agents Commander.app');
        fs.mkdirSync(path.join(appDir, 'Contents', 'MacOS'), { recursive: true });
        fs.writeFileSync(path.join(appDir, 'Contents', 'Info.plist'), plistXml(FIXTURE_EXE));
        if (job.id === 'I1') {
          fs.writeFileSync(
            path.join(appDir, 'Contents', 'MacOS', FIXTURE_EXE),
            'fixture executable placeholder\n',
          );
        }
        execFileSync(
          tarInfo.cmd,
          ['-czf', job.fixture, '-C', job.source, 'Agents Commander.app'],
          { cwd: workDir, stdio: 'pipe' },
        );
      }
    } catch (err) {
      fixtureError = `could not build fixture tarballs: ${err.message}`;
    }
  }

  for (const job of fixtureJobs) {
    if (fixtureError) {
      skip(job.id, fixtureError);
      continue;
    }
    test(job.id, () => {
      fs.rmSync(binDir, { recursive: true, force: true });
      const r = runInstall(job.fixture, tarInfo);
      if (job.id === 'I1') {
        expectExit(r, 0, 'I1');
        assertIncludes(r.stdout, 'Installation completed successfully.', 'I1 stdout');
        const exe = path.join(binDir, 'Agents Commander.app', 'Contents', 'MacOS', FIXTURE_EXE);
        assert(fs.existsSync(exe), `I1: expected installed executable at ${exe}`);
        assertNoInstallLeftovers('I1');
        return `installed ${exe}`;
      }
      expectExit(r, 1, 'I2');
      assertIncludes(r.stderr, 'Installation failed:', 'I2 stderr');
      assertIncludes(r.stderr, 'executable missing at', 'I2 stderr');
      const exe = path.join(binDir, 'Agents Commander.app', 'Contents', 'MacOS', FIXTURE_EXE);
      assertIncludes(r.stderr, exe, 'I2 stderr');
      assert(
        fs.existsSync(path.join(binDir, 'Agents Commander.app')),
        'I2: the incomplete bundle must stay in bin/ (decided partial state)',
      );
      assertNoInstallLeftovers('I2');
    });
  }
}

// ---------- main ----------

let failed = 0;
try {
  prepareWorkDir();
  console.log(
    `check-npm-launcher: host=${process.platform} fixture-exe=${FIXTURE_EXE} work-dir=${workDir}`,
  );
  runAllChecks();
} finally {
  if (ownsWorkDir && !keep) {
    fs.rmSync(workDir, { recursive: true, force: true });
  } else if (keep) {
    console.log(`work dir kept: ${workDir}`);
  }
}

for (const r of results) {
  console.log(`${r.status.padEnd(4)} ${r.id}${r.detail ? ' - ' + r.detail : ''}`);
}
const passed = results.filter((r) => r.status === 'PASS').length;
const skipped = results.filter((r) => r.status === 'SKIP').length;
failed = results.filter((r) => r.status === 'FAIL').length;
console.log(`\n${passed} passed, ${failed} failed, ${skipped} skipped`);
process.exitCode = failed > 0 ? 1 : 0;
