const NODE_BYTES = fs.readFileSync(process.execPath);
const CHILD_SCRIPT = "console.log('AC_MARKER:' + process.argv[1])";
const COPIED_FILES = ['run.js', 'install.js', 'resolve-bin.js', 'windows-shortcut.js', 'macos-alias.js', 'linux-desktop-entry.js'];
const COPIED_ASSETS = ['icon.png'];

