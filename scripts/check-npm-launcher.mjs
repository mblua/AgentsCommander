    expectEqual(desktopMod.entryPath({ HOME: '/h', XDG_DATA_HOME: '' }), entryFile(home), 'L1 empty XDG_DATA_HOME');
    expectEqual(desktopMod.entryPath({ HOME: '/h', XDG_DATA_HOME: '/data' }), entryFile('/data'), 'L1 XDG_DATA_HOME');
